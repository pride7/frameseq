#!/usr/bin/env node

/**
 * FrameSeq's icons are Lucide's (ISC licensed), read from @iconify-json/lucide. This module
 * turns that set into what a deck needs: SVG markup by name for the build, and the list of
 * names as a TypeScript type, so an editor completes icon names and TypeScript rejects a typo.
 *
 * Run it directly to regenerate src/icon-names.ts after updating the icon package.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

let cached;

/** Every icon as standalone SVG markup, keyed by name; aliases resolve to their icon. */
export function iconSet() {
  if (cached) return cached;
  const data = JSON.parse(readFileSync(require.resolve("@iconify-json/lucide/icons.json"), "utf8"));
  const width = data.width ?? 24;
  const height = data.height ?? 24;
  const markup = (icon) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${icon.width ?? width} ${icon.height ?? height}" width="1em" height="1em" aria-hidden="true">${icon.body}</svg>`;
  const icons = {};
  for (const [name, icon] of Object.entries(data.icons)) icons[name] = markup(icon);
  for (const [name, alias] of Object.entries(data.aliases ?? {})) {
    if (icons[alias.parent]) icons[name] = icons[alias.parent];
  }
  cached = icons;
  return icons;
}

/**
 * The icons themselves, once each, for a picker to draw: the inside of each SVG by name, and the
 * box they share. Aliases are left out, since each draws an icon already listed.
 */
export function iconBodies() {
  const data = JSON.parse(readFileSync(require.resolve("@iconify-json/lucide/icons.json"), "utf8"));
  const icons = {};
  for (const [name, icon] of Object.entries(data.icons)) icons[name] = icon.body;
  return { width: data.width ?? 24, height: data.height ?? 24, icons };
}

/** The icon names a source file may refer to: every string literal that is the name of an icon. */
export function iconNamesIn(source, icons = iconSet()) {
  const names = new Set();
  for (const match of source.matchAll(/["'`]([a-z0-9]+(?:-[a-z0-9]+)*)["'`]/g)) {
    if (icons[match[1]]) names.add(match[1]);
  }
  return names;
}

/** Whether a source file passes icon() something other than a string literal. */
export function namesIconsAtRuntime(source) {
  return /(?<![.\w$])icon\(\s*(?!["'`)\s])/.test(source)
    || /(?<![.\w$])icon\(\s*`[^`]*\$\{/.test(source);
}

export function iconNamesModule(icons = iconSet()) {
  const names = Object.keys(icons).sort();
  return `// Generated by scripts/icon-set.mjs from @iconify-json/lucide. Do not edit by hand.

/** The name of an icon in FrameSeq's set, Lucide's: https://lucide.dev/icons */
export type IconName =
${names.map((name) => `  | ${JSON.stringify(name)}`).join("\n")};
`;
}

if (process.argv[1] && /(?:^|[\\/])icon-set\.mjs$/.test(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const target = resolve(packageRoot, "src", "icon-names.ts");
  writeFileSync(target, iconNamesModule(), "utf8");
  console.log(`Wrote ${Object.keys(iconSet()).length} icon names to ${target}`);
}
